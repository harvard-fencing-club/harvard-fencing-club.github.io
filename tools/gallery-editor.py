"""Gallery editor: arrange the Gallery and pick front-page photos in your browser.

    python tools/gallery-editor.py        (then open http://localhost:4001)

Drag photos between collections, split or merge collections, reorder them, mark extra big
tiles, choose the cover photo, star front-page photos, and rotate sideways ones. "Save"
writes tools/gallery-layout.json (kept by later runs of update-photos.py) and updates
assets/js/photos.js straight away, so `jekyll serve` shows the result on refresh.
Standard library only; it never contacts Google Drive.
"""
import ast
import http.server
import json
import pathlib
import re
import webbrowser

TOOLS = pathlib.Path(__file__).resolve().parent
PHOTOS = TOOLS.parent / "assets" / "js" / "photos.js"
LAYOUT = TOOLS / "gallery-layout.json"
PAGE = TOOLS / "gallery-editor.html"
PORT = 4001
ID = re.compile(r"^[A-Za-z0-9_-]{10,200}$")


def read_photos():
    text = PHOTOS.read_text(encoding="utf-8")
    header, _, body = text.partition("window.CLUB_PHOTOS = ")
    return header, json.loads(body.strip().rstrip(";"))


def home_focus():
    """HOME_FOCUS from update-photos.py (slideshow framing per photo)."""
    tree = ast.parse((TOOLS / "update-photos.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "HOME_FOCUS" for t in node.targets):
            return ast.literal_eval(node.value)
    return {}


def state():
    _, data = read_photos()
    gallery = data["gallery"]
    featured = set(gallery.get("featured", []))
    collections = [{"photos": group, "big": bool(featured & set(group))} for group in gallery["groups"]]
    return {
        "collections": collections,
        "home": data["home"]["ids"],
        "rotate": data.get("rotate", {}),
        "ids": gallery["ids"],
        "folders": gallery.get("folders", []),
    }


def save(payload):
    _, data = read_photos()
    known = set(data["gallery"]["ids"])
    collections, seen = [], set()
    for c in payload["collections"]:
        photos = [p for p in c["photos"] if p in known and p not in seen]
        seen.update(photos)
        if photos:
            collections.append({"photos": photos, "big": bool(c.get("big"))})
    missing = [p for p in data["gallery"]["ids"] if p not in seen]
    if missing:  # never lose a photo: anything not placed becomes its own collection at the end
        collections += [{"photos": [p], "big": False} for p in missing]
    home = [p for p in dict.fromkeys(payload.get("home", [])) if ID.match(p)]
    rotate = {p: r for p, r in payload.get("rotate", {}).items() if p in known and r in (90, 180, 270)}
    layout = {"collections": collections, "home": home, "rotate": rotate}
    LAYOUT.write_text(json.dumps(layout, indent=1) + "\n", encoding="utf-8")

    data["gallery"]["groups"] = [c["photos"] for c in collections]
    data["gallery"]["featured"] = [c["photos"][0] for c in collections if c["big"]]
    data["gallery"]["autoBig"] = True  # every 10th collection is big too
    data["rotate"] = rotate
    if home:
        focus = home_focus()
        data["home"]["ids"] = home
        data["home"]["focus"] = {p: focus[p] for p in home if p in focus}
    with open(PHOTOS, "w", encoding="utf-8", newline="\n") as file:
        file.write("// Generated by update-photos.py — do not edit by hand. Rerun tools/update-photos.py after changing the Drive folders.\n")
        file.write("window.CLUB_PHOTOS = " + json.dumps(data, separators=(",", ":")) + ";\n")
    return {"collections": len(collections), "home": len(home), "rotated": len(rotate)}


class Handler(http.server.BaseHTTPRequestHandler):
    def reply(self, code, body, kind="application/json"):
        raw = body if isinstance(body, bytes) else json.dumps(body).encode()
        self.send_response(code)
        self.send_header("Content-Type", kind)
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(raw)

    def do_GET(self):
        if self.path in ("/", "/index.html"):
            self.reply(200, PAGE.read_bytes(), "text/html; charset=utf-8")
        elif self.path == "/state":
            self.reply(200, state())
        else:
            self.reply(404, {"error": "not found"})

    def do_POST(self):
        if self.path != "/save":
            return self.reply(404, {"error": "not found"})
        try:
            payload = json.loads(self.rfile.read(int(self.headers.get("Content-Length", 0))))
            result = save(payload)
            print(f"saved: {result}", flush=True)
            self.reply(200, result)
        except Exception as error:  # report problems to the page instead of crashing
            self.reply(400, {"error": str(error)})

    def log_message(self, *args):
        pass


if __name__ == "__main__":
    server = http.server.ThreadingHTTPServer(("127.0.0.1", PORT), Handler)
    print(f"Gallery editor: http://localhost:{PORT}  (Ctrl+C to stop)", flush=True)
    try:
        webbrowser.open(f"http://localhost:{PORT}")
    except Exception:
        pass
    server.serve_forever()
